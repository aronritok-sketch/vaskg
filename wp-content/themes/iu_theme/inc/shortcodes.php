    function site_url(){
        return site_url('/');
    }

    function year(){
    	return date('Y');
    }

    function post_title(){
        return get_the_title();
    }

    function post_excerpt($atts){
        $atts = wp_parse_args($atts,[
            'words' => 21
        ]);

        if (empty($excerpt = get_the_excerpt())){
            return wp_trim_words(get_the_content(), $atts['words'], ' (...)');
        } else {
            return wp_trim_words($excerpt, $atts['words'], ' (...)');
        }
    }

    function post_link(){
        return get_permalink();
    }

    function post_featured_image_link($atts){
        global $post;

        $atts = wp_parse_args($atts,[
            'size' => 'full'
        ]);
        
        return wp_get_attachment_image_url(get_post_thumbnail_id($post->ID), $atts['size']);
    }

    function post_date($atts){
        global $post;

        $atts = wp_parse_args($atts,[
            'format' => get_option('date_format') . ' ' . get_option('time_format')
        ]);

        return wp_date($atts['format'], strtotime($post->post_date));
    }

    function post_category(){
        global $post;

        $category = get_the_category($post->ID)[0];
        return '<a class="iu-post-category" href="'.get_category_link($category).'">'.$category->name.'</a>';
